#!/usr/bin/env python3
"""Generate CMakePresets.json and docs/renderers.md from cmake/renderers.json.

cna-c-template deliberately keeps one renderer manifest and derives everything
else from it, so a renderer cannot be listed correctly in one place and wrongly
in another.

    python3 tools/gen_renderer_files.py            # regenerate
    python3 tools/gen_renderer_files.py --check     # fail if anything is stale

--check is what CI runs. It regenerates into memory and compares, so a manifest
edit that was not followed by a regeneration is caught as a diff rather than
silently shipping inconsistent presets.

The manifest does not own the renderer *names*: CNA does. This script also
cross-checks the manifest against CNA's own canonical list when a CNA checkout
is reachable, using the same line cna/cmake/RendererSelection.cmake declares.
That check affects the exit status but never the generated bytes, so generation
is reproducible whether or not a sibling checkout happens to exist.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

try:
    # Direct script execution puts tools/ on sys.path.
    from dependency_pins import load_pins
except ModuleNotFoundError:
    # Unit-test/import usage puts the repository root on sys.path instead.
    from tools.dependency_pins import load_pins

REPO = Path(__file__).resolve().parent.parent
MANIFEST = REPO / "cmake" / "renderers.json"
PRESETS = REPO / "CMakePresets.json"
RENDERER_DOC = REPO / "docs" / "renderers.md"

# Where CNA's canonical list lives, relative to a CNA checkout.
# Current CNA keeps the public inventory in cmake/RendererIdentities.cmake (RRC-018 moved it
# there and retired the rest); older checkouts spelled it as the cache variable's STRINGS in
# RendererSelection.cmake. Read the registry first, the STRINGS line only as a fallback.
CNA_IDENTITIES_FILE = Path("cmake") / "RendererIdentities.cmake"
CNA_IDENTITIES_RE = re.compile(r"set\(CNA_RENDERER_PUBLIC_IDENTITIES\s+([A-Z0-9_\s]+)\)")
CNA_RENDERER_FILE = Path("cmake") / "RendererSelection.cmake"
CNA_STRINGS_RE = re.compile(
    r'set_property\(CACHE CNA_GRAPHICS_RENDERER PROPERTY STRINGS((?:\s+"[A-Z0-9_]+")+)\)'
)

CATEGORY_TITLES = {
    "sdl": "SDL",
    "gl-easygl": "OpenGL family (shared EasyGL implementation)",
    "gl-native": "OpenGL family (native, no EasyGL)",
    "modern-gpu": "Modern GPU APIs",
    "cpu": "CPU / diagnostic",
    "raster-2d": "2D vector rasterizers",
    "web-dom": "Browser DOM",
    "middleware": "Portable middleware",
    "legacy-api": "Legacy APIs",
    "directx": "DirectX",
}

PLATFORM_TITLES = {
    "linux": "Linux",
    "windows": "Windows",
    "macos": "macOS",
    "web": "Web",
    "android": "Android",
}

TIER_TEXT = {
    "B": "baseline selection",
    "C": "broad-matrix candidate",
    "D": "on demand",
    "X": "not on CI runners",
}

REQUIRED_FIELDS = {
    "name",
    "category",
    "dimension",
    "platforms",
    "gate",
    "display",
    "dependency",
    "tier",
    "preset",
    "notes",
}
OPTIONAL_FIELDS = {"experimental", "webflags"}
TOP_LEVEL_FIELDS = {"$comment", "renderers"}
DESKTOP_PLATFORM_HOSTS = {
    "linux": "Linux",
    "windows": "Windows",
    "macos": "Darwin",
}


def load_manifest() -> list[dict]:
    data = json.loads(MANIFEST.read_text())
    if not isinstance(data, dict):
        raise ValueError("cmake/renderers.json must contain a top-level object")
    unknown_top_level = data.keys() - TOP_LEVEL_FIELDS
    if unknown_top_level:
        raise ValueError(
            "cmake/renderers.json has unknown top-level field(s): "
            + ", ".join(sorted(unknown_top_level))
        )
    comments = data.get("$comment", [])
    if not isinstance(comments, list) or not all(
        isinstance(comment, str) for comment in comments
    ):
        raise ValueError("cmake/renderers.json field '$comment' must be an array of strings")
    renderers = data.get("renderers")
    if not isinstance(renderers, list) or not renderers:
        raise ValueError("cmake/renderers.json must contain a non-empty 'renderers' array")
    validate_manifest(renderers)
    return renderers


def validate_manifest(renderers: list[dict]) -> None:
    """Reject malformed metadata before it can create plausible-looking output."""
    names: set[str] = set()
    for index, renderer in enumerate(renderers):
        if not isinstance(renderer, dict):
            raise ValueError(f"renderer entry {index} must be an object")
        missing = REQUIRED_FIELDS - renderer.keys()
        if missing:
            raise ValueError(
                f"renderer entry {index} is missing field(s): {', '.join(sorted(missing))}"
            )
        unknown = renderer.keys() - REQUIRED_FIELDS - OPTIONAL_FIELDS
        if unknown:
            raise ValueError(
                f"renderer entry {index} has unknown field(s): "
                + ", ".join(sorted(unknown))
            )

        name = renderer["name"]
        if not isinstance(name, str) or not re.fullmatch(r"[A-Z0-9_]+", name):
            raise ValueError(f"renderer entry {index} has invalid name {name!r}")
        if name in names:
            raise ValueError(f"renderer name {name!r} appears more than once")
        names.add(name)

        category = renderer["category"]
        if not isinstance(category, str) or category not in CATEGORY_TITLES:
            raise ValueError(f"renderer {name} has unknown category {category!r}")
        if not isinstance(renderer["dimension"], str) or renderer["dimension"] not in {
            "2d",
            "2d3d",
        }:
            raise ValueError(f"renderer {name} has invalid dimension {renderer['dimension']!r}")
        if not isinstance(renderer["display"], str) or renderer["display"] not in {
            "window",
            "none",
        }:
            raise ValueError(f"renderer {name} has invalid display {renderer['display']!r}")
        if not isinstance(renderer["gate"], str) or renderer["gate"] not in {
            "fatal",
            "warn",
            "none",
        }:
            raise ValueError(f"renderer {name} has invalid gate {renderer['gate']!r}")
        if not isinstance(renderer["tier"], str) or renderer["tier"] not in TIER_TEXT:
            raise ValueError(f"renderer {name} has unknown CI tier {renderer['tier']!r}")
        if not isinstance(renderer["preset"], bool):
            raise ValueError(f"renderer {name} field 'preset' must be a boolean")
        for text_field in ("dependency", "notes"):
            if not isinstance(renderer[text_field], str) or not renderer[text_field].strip():
                raise ValueError(f"renderer {name} field {text_field!r} must be non-empty text")

        platforms = renderer["platforms"]
        if (
            not isinstance(platforms, list)
            or not platforms
            or not all(isinstance(platform, str) for platform in platforms)
        ):
            raise ValueError(f"renderer {name} must list at least one platform")
        unknown_platforms = set(platforms) - PLATFORM_TITLES.keys()
        if unknown_platforms:
            raise ValueError(
                f"renderer {name} has unknown platform(s): "
                + ", ".join(sorted(unknown_platforms))
            )
        if len(platforms) != len(set(platforms)):
            raise ValueError(f"renderer {name} lists a platform more than once")

        experimental = renderer.get("experimental", [])
        if not isinstance(experimental, list) or not all(
            isinstance(platform, str) for platform in experimental
        ):
            raise ValueError(
                f"renderer {name} field 'experimental' must be an array of platforms"
            )
        unknown_experimental = set(experimental) - PLATFORM_TITLES.keys()
        if unknown_experimental:
            raise ValueError(
                f"renderer {name} has unknown experimental platform(s): "
                + ", ".join(sorted(unknown_experimental))
            )
        if len(experimental) != len(set(experimental)):
            raise ValueError(f"renderer {name} lists an experimental platform more than once")
        overlap = set(platforms) & set(experimental)
        if overlap:
            raise ValueError(
                f"renderer {name} lists platform(s) as both supported and experimental: "
                + ", ".join(sorted(overlap))
            )

        webflags = renderer.get("webflags", [])
        if not isinstance(webflags, list) or not all(
            isinstance(flag, str) and flag for flag in webflags
        ):
            raise ValueError(f"renderer {name} field 'webflags' must be an array of strings")
        if len(webflags) != len(set(webflags)):
            raise ValueError(f"renderer {name} lists a web flag more than once")
        if webflags and "web" not in platforms:
            raise ValueError(f"renderer {name} has webflags but is not supported on web")


def default_cna_candidates() -> tuple[Path, Path]:
    """The dependency layout shared by CMake, Android, and this generator."""
    directory = load_pins()["CNA"].directory
    return REPO.parent / directory, REPO.parent.parent / directory


def find_cna_root(explicit: Path | None) -> Path | None:
    """Resolve an explicit checkout or find the normal sibling layout."""
    if explicit is not None:
        candidate = explicit if explicit.is_absolute() else REPO / explicit
        candidate = candidate.resolve()
        if not (candidate / "CMakeLists.txt").is_file():
            raise ValueError(
                f"--cna-root {explicit!s} does not identify a CNA checkout "
                f"(missing {candidate / 'CMakeLists.txt'})"
            )
        return candidate

    for candidate in default_cna_candidates():
        if (candidate / "CMakeLists.txt").is_file():
            return candidate.resolve()
    return None


def canonical_from_cna(cna_root: Path) -> list[str]:
    """Read CNA's own renderer list, failing if its declared format changed."""
    identities = cna_root / CNA_IDENTITIES_FILE
    path = cna_root / CNA_RENDERER_FILE
    if identities.is_file():
        match = CNA_IDENTITIES_RE.search(identities.read_text())
        if not match:
            raise ValueError(
                "could not parse CNA_RENDERER_PUBLIC_IDENTITIES from "
                f"{identities}; update CNA_IDENTITIES_RE instead of silently skipping the cross-check"
            )
        names = match.group(1).split()
        path = identities
    else:
        if not path.is_file():
            raise ValueError(f"CNA renderer selection file is missing: {path}")
        match = CNA_STRINGS_RE.search(path.read_text())
        if not match:
            raise ValueError(
                "could not parse CNA's canonical renderer list from "
                f"{path}; update CNA_STRINGS_RE instead of silently skipping the cross-check"
            )
        names = re.findall(r'"([A-Z0-9_]+)"', match.group(1))
    if len(names) != len(set(names)):
        raise ValueError(f"CNA's canonical renderer list contains a duplicate name: {path}")
    return names


def slug(name: str) -> str:
    return name.lower().replace("_", "-")


def host_condition(platforms: list[str]) -> dict:
    """Build a literal preset condition from supported desktop platform tokens."""
    hosts = [
        host
        for platform, host in DESKTOP_PLATFORM_HOSTS.items()
        if platform in platforms
    ]
    if not hosts:
        raise ValueError(
            "cannot generate a native preset without a supported desktop host"
        )
    if len(hosts) == 1:
        return {
            "type": "equals",
            "lhs": "${hostSystemName}",
            "rhs": hosts[0],
        }
    return {
        "type": "inList",
        "string": "${hostSystemName}",
        "list": hosts,
    }


def check_against_cna(
    renderers: list[dict], cna_root: Path | None
) -> tuple[bool, list[str]]:
    """Return (in-sync, diagnostics) for the optional CNA cross-check."""
    if cna_root is None:
        return True, ["note: no CNA checkout found; renderer names were not cross-checked"]
    canonical = canonical_from_cna(cna_root)

    ours = [r["name"] for r in renderers]
    missing = [n for n in canonical if n not in ours]
    extra = [n for n in ours if n not in canonical]

    problems: list[str] = []
    if missing:
        problems.append(
            f"{len(missing)} renderer(s) in CNA but missing from the manifest: "
            + ", ".join(missing)
        )
    if extra:
        problems.append(
            f"{len(extra)} renderer(s) in the manifest but not in CNA: " + ", ".join(extra)
        )
    if not problems:
        return True, [
            f"ok: manifest matches CNA's {len(canonical)} canonical renderers at {cna_root}"
        ]
    return False, problems


