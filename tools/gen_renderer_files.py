# CMakePresets.json
# --------------------------------------------------------------------------
def build_presets(renderers: list[dict]) -> dict:
    configure = [
        {
            "name": "base",
            "hidden": True,
            "cacheVariables": {"CMAKE_BUILD_TYPE": "Debug"},
        },
        {
            "name": "release",
            "hidden": True,
            "cacheVariables": {"CMAKE_BUILD_TYPE": "Release"},
        },
        {
            "name": "web-base",
            "hidden": True,
            "inherits": "release",
            # Lets `cmake --preset web-*` work directly instead of via emcmake.
            "toolchainFile": "$env{EMSDK}/upstream/emscripten/cmake/Modules/Platform/Emscripten.cmake",
            "condition": host_condition(list(DESKTOP_PLATFORM_HOSTS)),
        },
        {
            "name": "mingw-base",
            "hidden": True,
            "inherits": "base",
            "toolchainFile": "${sourceDir}/cmake/toolchains/mingw-w64.cmake",
            "condition": {
                "type": "equals",
                "lhs": "${hostSystemName}",
                "rhs": "Linux",
            },
        },
    ]
    build = []
    test = []

    def add_renderer_route(
        renderer: dict,
        preset_name: str,
        inherits: str,
        configuration: str,
        condition: dict,
        runnable: bool,
    ) -> None:
        platforms = renderer["platforms"]
        name = renderer["name"]
        entry = {
            "name": preset_name,
            # First sentence of the note, split on ". " so "GLES 2.0" survives.
            "displayName": f"{name} — {renderer['notes'].split('. ')[0].rstrip('.')}",
            "description": (
                f"{renderer['dimension'].upper()} renderer. "
                f"Platforms: {', '.join(platforms)}. "
                f"Dependency: {renderer['dependency']}."
            ),
            "inherits": inherits,
            "binaryDir": "${sourceDir}/build-" + preset_name,
            "cacheVariables": {"CNA_GRAPHICS_RENDERER": name},
            "condition": condition,
        }
        configure.append(entry)
        build.append(
            {
                "name": preset_name,
                "configurePreset": preset_name,
                "configuration": configuration,
                "condition": condition,
            }
        )

        if runnable:
            test.append(
                {
                    "name": preset_name,
                    "configurePreset": preset_name,
                    "configuration": configuration,
                    "output": {"outputOnFailure": True},
                    "execution": {"noTestsAction": "error"},
                    "filter": {
                        "include": {
                            "label": "headless"
                            if renderer["display"] == "none"
                            else "display"
                        }
                    },
                    "condition": condition,
                }
            )

    for renderer in renderers:
        if not renderer.get("preset"):
            continue

        platforms = renderer["platforms"]
        if platforms == ["web"]:
            # Emscripten output cannot run directly under the configuring host.
            add_renderer_route(
                renderer,
                f"web-{slug(renderer['name'])}",
                "web-base",
                "Release",
                host_condition(list(DESKTOP_PLATFORM_HOSTS)),
                False,
            )
            continue

        # Native routes derive visibility from every declared desktop target
        # platform. Android is configured by Gradle and is deliberately ignored.
        add_renderer_route(
            renderer,
            slug(renderer["name"]),
            "base",
            "Debug",
            host_condition(platforms),
            True,
        )

        if platforms == ["windows"]:
            # Retain the convenient Linux-to-Windows route as a separate preset;
            # unlike the native Windows route, its binaries are not runnable here.
            add_renderer_route(
                renderer,
                f"windows-{slug(renderer['name'])}",
                "mingw-base",
                "Debug",
                host_condition(["linux"]),
                False,
            )

    return {
        "version": 3,
        "cmakeMinimumRequired": {"major": 3, "minor": 23, "patch": 0},
        "configurePresets": configure,
        "buildPresets": build,
        "testPresets": test,
    }


# --------------------------------------------------------------------------
# docs/renderers.md
# --------------------------------------------------------------------------
def build_doc(renderers: list[dict]) -> str:
    count = len(renderers)
    no_display = [renderer["name"] for renderer in renderers if renderer["display"] == "none"]
    no_display_text = ", ".join(f"`{name}`" for name in no_display)

    out: list[str] = []
    add = out.append

    add("<!-- GENERATED FILE — do not edit by hand. -->")
    add("<!-- Source: cmake/renderers.json — regenerate with tools/gen_renderer_files.py -->")
    add("")
    add("# CNA renderers")
    add("")
    add(
        f"CNA currently exposes **{count} renderers**. You pick one at configure time "
        "with a single cache variable:"
    )
    add("")
    add("```bash")
    add("cmake -S . -B build -DCNA_GRAPHICS_RENDERER=OPENGLES3")
    add("```")
    add("")
    add(
        "If you set nothing, CNA chooses for you: `WEBGL2` on the web, `OPENGLES3` on "
        "Linux, `SDL_RENDERER` everywhere else."
    )
    add("")
    add("## How to read this")
    add("")
    add(
        "**Platforms** are where the renderer is supported. cna-template refuses, with an "
        "explanation, to configure a renderer for a platform not listed here. A few "
        "renderers additionally have *experimental* platforms — CNA permits them but does "
        "not support them, so the template warns instead of refusing."
    )
    add("")
    add(
        "**Display** says whether the renderer opens a window. Renderers marked **none** "
        f"({no_display_text}) need no X server, no GPU and no "
        "video driver, which makes them the right choice for CI and servers. Note that "
        "`SOFTWARE` and `PORTABLEGL` genuinely rasterize but present nowhere."
    )
    add("")
    add(
        "**Scope** is `2D` or `2D+3D`. On a 2D-only renderer the 3D calls "
        "(for example `cna_vertex_buffer_create(...)`, "
        "`cna_graphics_device_draw_user_primitives(...)`, and depth/stencil operations) "
        "return `CNA_RESULT_NOT_SUPPORTED`. Query "
        "`cna_graphics_device_supports_capability(...)` with "
        "`CNA_GRAPHICS_CAPABILITY_THREE_D` or the narrower capability at runtime "
        "rather than testing the renderer's name."
    )
    add("")
    add(
        "**CI tier** is scheduling metadata for this template, not evidence of CNA support or a "
        "claim that every renderer was run in the current checkout: *baseline selection*, "
        "*broad-matrix candidate*, *on demand*, or *not on CI runners*."
    )
    add("")

    by_category: dict[str, list[dict]] = {}
    for renderer in renderers:
        by_category.setdefault(renderer["category"], []).append(renderer)

    for category, title in CATEGORY_TITLES.items():
        group = by_category.get(category)
        if not group:
            continue
        add(f"## {title}")
        add("")
        add("| Renderer | Platforms | Scope | Display | Dependency | CI tier | Notes |")
        add("| --- | --- | --- | --- | --- | --- | --- |")
        for renderer in group:
            platforms = ", ".join(PLATFORM_TITLES[p] for p in renderer["platforms"])
            experimental = renderer.get("experimental") or []
            if experimental:
                platforms += " (+ " + ", ".join(
                    PLATFORM_TITLES[p] for p in experimental
                ) + " experimental)"
            scope = "2D+3D" if renderer["dimension"] == "2d3d" else "2D"
            display = "window" if renderer["display"] == "window" else "**none**"
            tier_text = TIER_TEXT.get(renderer["tier"], renderer["tier"])
            preset = f"`{slug(renderer['name'])}`" if renderer.get("preset") else "—"
            add(
                f"| `{renderer['name']}` | {platforms} | {scope} | {display} | "
                f"{renderer['dependency']} | {tier_text} | {renderer['notes']} |"
            )
            del preset
        add("")

    add("## Presets")
    add("")
    add(
        "Renderers in common use have a ready-made preset; the rest are selected with "
        "`-DCNA_GRAPHICS_RENDERER=<NAME>` against any preset or a plain build directory. "
        "Every one of the "
        f"{count} renderers above is selectable either way."
    )
    add("")
    add("```bash")
    add("cmake --list-presets                 # what is available")
    add("cmake --preset opengles3             # configure")
    add("cmake --build --preset opengles3     # build")
    add("ctest --preset opengles3             # smoke test")
    add("```")
    add("")
    add(
        "Native configure, build, and runnable test presets all receive the same host condition, "
        "derived from every supported desktop platform above. Android uses Gradle instead. Web "
        "presets are cross-build routes available on Linux, Windows, and macOS hosts. Runnable "
        "test presets treat zero discovered tests as an error. Native and MinGW build presets "
        "select `Debug`; web build presets select `Release`. Native test presets select the same "
        "configuration as their associated build preset, including with multi-config generators."
    )
    add("")
    add(
        "Windows-only renderers have native Windows presets plus `windows-directx*` MinGW "
        "cross-build routes on Linux. Web and MinGW routes intentionally have no CTest preset "
        "because their binaries cannot execute directly on the configuring host."
    )
    add("")

    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the generated files are up to date instead of writing them",
    )
    parser.add_argument(
        "--ci-matrix",
        metavar="PLATFORM",
        choices=tuple(PLATFORM_TITLES),
        help="print a GitHub Actions matrix of renderers for PLATFORM and exit",
    )
    parser.add_argument(
        "--tiers",
        default=None,
        help="comma-separated CI tiers to include with --ci-matrix (default: B)",
    )
    parser.add_argument(
        "--cna-root",
        type=Path,
        help=(
            "CNA checkout to cross-check; by default ../cna then ../../cna are tried "
            "relative to the template root"
        ),
    )
    args = parser.parse_args()

    if args.tiers is not None and args.ci_matrix is None:
        parser.error("--tiers is only valid together with --ci-matrix")

    try:
        renderers = load_manifest()
    except (OSError, json.JSONDecodeError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    # Lets the CI workflow build its matrix from the manifest instead of
    # repeating a renderer list in YAML, where it would drift unnoticed.
    if args.ci_matrix:
        tier_argument = args.tiers if args.tiers is not None else "B"
        tiers = {tier.strip() for tier in tier_argument.split(",") if tier.strip()}
        if not tiers:
            parser.error("--tiers must select at least one CI tier")
        unknown_tiers = tiers - TIER_TEXT.keys()
        if unknown_tiers:
            parser.error(
                "unknown CI tier(s): "
                + ", ".join(sorted(unknown_tiers))
                + "; expected one or more of "
                + ", ".join(TIER_TEXT)
            )
        selected = [
            r["name"]
            for r in renderers
            if args.ci_matrix in r["platforms"] and r["tier"] in tiers
        ]
        print(json.dumps(selected))
        return 0

    try:
        cna_root = find_cna_root(args.cna_root)
        semantic_ok, semantic_diagnostics = check_against_cna(renderers, cna_root)
    except (OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    for line in semantic_diagnostics:
        print(line)

    wanted = {
        PRESETS: json.dumps(build_presets(renderers), indent=2) + "\n",
        RENDERER_DOC: build_doc(renderers),
    }

    if args.check:
        stale = []
        for path, content in wanted.items():
            current = path.read_text() if path.exists() else None
            if current != content:
                stale.append(path.relative_to(REPO))
        if stale:
            print()
            print("Stale generated file(s): " + ", ".join(str(p) for p in stale))
            print("Run: python3 tools/gen_renderer_files.py")
        if not semantic_ok:
            print()
            print("Renderer manifest does not match CNA; update cmake/renderers.json first.")
        if stale or not semantic_ok:
            return 1
        print(f"ok: {len(wanted)} generated file(s) up to date")
        return 0

    if not semantic_ok:
        print("Renderer manifest does not match CNA; refusing to generate known-inconsistent files.")
        return 1

    for path, content in wanted.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
